#!/usr/bin/env node
/**
 * Generates backend/prisma/schema.dev.prisma from schema.prisma with the
 * datasource provider switched to sqlite for local development.
 *
 * Why: Prisma requires a static datasource provider, so one schema file cannot
 * serve both SQLite (dev) and PostgreSQL (prod). The schema is the single source
 * of truth; only the provider line differs. Production never uses this file.
 */
const fs = require('node:fs');
const path = require('node:path');

const backend = path.join(__dirname, '..', 'backend');
const source = path.join(backend, 'prisma', 'schema.prisma');
const target = path.join(backend, 'prisma', 'schema.dev.prisma');

if (!fs.existsSync(source)) {
  console.error(`[use-sqlite] schema not found: ${source}`);
  process.exit(1);
}

const schema = fs.readFileSync(source, 'utf8');
if (!/provider\s*=\s*"postgresql"/.test(schema)) {
  console.error('[use-sqlite] expected provider = "postgresql" in schema.prisma');
  process.exit(1);
}

const dev = schema.replace(/provider\s*=\s*"postgresql"/, 'provider = "sqlite"');
const banner =
  '// AUTO-GENERATED by scripts/use-sqlite.cjs - do not edit, do not commit.\n' +
  '// Source of truth: prisma/schema.prisma (postgresql, used in production).\n';
fs.writeFileSync(target, banner + dev, 'utf8');
console.log(`[use-sqlite] wrote ${path.relative(process.cwd(), target)} (sqlite)`);
